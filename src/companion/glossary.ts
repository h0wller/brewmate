export function findTerm(id: string): Term | undefined {
  return TERMS.find(t => t.id === id)
}

export function searchTerms(q: string): Term[] {
  const s = q.trim().toLowerCase()
  if (!s) return TERMS
  return TERMS.filter(t => (t.title + ' ' + t.short).toLowerCase().includes(s))
}